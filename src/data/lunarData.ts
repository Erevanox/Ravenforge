export function isVisibleInRange(
  record: LunarObject,
  startYear: number,
  endYear: number,
): boolean {
  const start = Number(startYear);
  const end = Number(endYear);

  if (record.objectType === 'orbiter' || record.objectType === 'mission-event') {
    const operationalStart = record.operationalStartDate ? new Date(record.operationalStartDate).getFullYear() : start;
    const operationalEnd = record.operationalEndDate
      ? new Date(record.operationalEndDate).getFullYear()
      : end;
    return operationalStart <= end && operationalEnd >= start;
  }

  const presenceStart = record.physicalPresenceStartDate
    ? new Date(record.physicalPresenceStartDate).getFullYear()
    : Number.NEGATIVE_INFINITY;
  const presenceEnd = record.physicalPresenceEndDate
    ? new Date(record.physicalPresenceEndDate).getFullYear()
    : Number.POSITIVE_INFINITY;

  return presenceStart <= end && presenceEnd >= start;
}
